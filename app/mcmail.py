def _date_en(d, long: bool = True) -> str:
    m = re.match(r"^(\d{4})-(\d{2})-(\d{2})$", d or "")
    if not m:
        return d or ""
    name = _MONTHS_EN[int(m[2]) - 1]
    return f"{name if long else name[:3]} {int(m[3])}"


