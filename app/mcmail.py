@contextmanager
def _using(st: _State | None, write: bool = False):
    if st is not None:
        yield st
    else:
        with _session(write) as s:
            yield s


def erp_price(customer_code, item_code, qty, st: _State | None = None) -> dict:
    """단가 조회(구간 할인 300/500/1000 → 5/8/12%) / price lookup with tier discounts"""
    with _using(st) as s:
        if customer_code not in ERP_CUSTOMERS:
            return {"error": "Customer Code를 찾을 수 없습니다."}
        it = s.items.get(item_code)
        if not it:
            return {"error": "Item Code가 ERP에 등록되어 있지 않습니다."}
        q = _number(qty)
        if q is None or not (q > 0) or not _is_int(q):
            return {"error": "수량 값이 올바르지 않습니다."}
        q = int(q)
        rate = next((t[1] for t in TIERS if q >= t[0]), 0)
        price = _round(it["base"] * (1 - rate) / 10) * 10
        in_stock = q <= it["stock"]
        return {"itemName": it["name"], "short": it["short"], "itemCode": item_code, "base": it["base"], "price": price,
                "rate": rate, "qty": q, "stock": it["stock"], "inStock": in_stock,
                "lead": it["lead"] if in_stock else it["leadBack"]}


def erp_stock(item_code, qty=None, st: _State | None = None) -> dict:
    """On-hand 재고 조회 / on-hand stock lookup"""
    with _using(st) as s:
        it = s.items.get(item_code)
        if not it:
            return {"error": "Item Code가 ERP에 등록되어 있지 않습니다."}
        alloc = _round(it["stock"] * .18 / 10) * 10
        avail = it["stock"] - alloc
        n = _number(qty)
        req = n if n is not None and n > 0 else 0
        return {"itemName": it["name"], "short": it["short"], "itemCode": item_code, "onHand": it["stock"],
                "allocated": alloc, "available": avail, "reqQty": req, "enough": (not req) or req <= avail,
                "inboundDate": _add_days(it["lead"], -6), "inboundQty": 1500, "warehouse": "화성 제1물류센터",
                "asOf": f"{s.today} {_hhmm(s.clock)}"}


def erp_sales_order(so, customer_code=None, st: _State | None = None) -> dict:
    """Sales Order 조회 → 인보이스 정보 / sales-order lookup → invoice figures"""
    with _using(st) as s:
        so = _s(so).strip()
        sh = s.shipments.get(so)
        if not sh:
            return {"error": f"Sales Order {so or '(번호 없음)'} 를 ERP에서 찾을 수 없습니다."}
        if _js(customer_code) and sh["customerCode"] != customer_code:
            return {"error": f"{so} 는 다른 고객({ERP_CUSTOMERS.get(sh['customerCode'])})의 주문입니다. 인보이스를 발송할 수 없습니다."}
        c = next((c for c in s.cases if c.get("salesOrderNumber") == so), None)
        it = s.items.get(sh["itemCode"])
        price = (c or {}).get("entity", {}).get("unitPrice") if c else None
        if not _js(price):
            price = erp_price(sh["customerCode"], sh["itemCode"], sh["orderQty"], s).get("price") or 0
        amount = price * sh["orderQty"]
        vat = _round(amount * .1)
        cust = ERP_CUSTOMERS.get(sh["customerCode"])
        return {"so": so, "invoiceNo": "INV-" + so[3:], "customer": cust, "customerCode": sh["customerCode"],
                "itemName": (it or {}).get("name") or sh["item"], "short": sh["item"], "itemCode": sh["itemCode"],
                "qty": sh["orderQty"], "price": price, "amount": amount, "vat": vat, "total": amount + vat,
                "orderDate": f"{so[3:7]}-{so[7:9]}-{so[9:11]}",
                "deliveryDate": ((c or {}).get("entity") or {}).get("deliveryDate") or "",
                "state": sh["state"],
                "billTo": ((c or {}).get("entity") or {}).get("shippingAddress") or (CONTACTS.get(cust) or {}).get("addr") or ""}


def erp_shipment(so=None, customer_code=None, item_code=None, case_id=None, st: _State | None = None) -> dict:
    """출하내역 조회 — 매칭 4순위(SO → 고객+품목 → 고객 최근 주문 → Case 의 주문) / shipment lookup, 4 match priorities"""
    with _using(st) as s:
        so = _s(so).strip()
        c = s.case(case_id)
        if so and so in s.shipments:
            return {"matchedBy": 1, **s.shipments[so]}
        if so:
            return {"error": f"Sales Order {so} 를 ERP에서 찾을 수 없습니다."}
        allsh = list(s.shipments.values())
        r = next((x for x in allsh if x["customerCode"] == customer_code and x["itemCode"] == item_code), None)
        if r:
            return {"matchedBy": 2, **r}
        mine = sorted([x for x in allsh if x["customerCode"] == customer_code], key=lambda x: x["so"], reverse=True)
        if mine:
            return {"matchedBy": 3, **mine[0]}
        cso = (c or {}).get("salesOrderNumber")
        if _js(cso) and cso in s.shipments:
            return {"matchedBy": 4, **s.shipments[cso]}
        return {"error": "조건에 해당하는 출하내역을 ERP에서 찾을 수 없습니다."}


def _validate_values(cc: str, icode: str, qty, dd: str, today: str, items: dict) -> str:
    if cc not in ERP_CUSTOMERS:
        return "Customer Code를 찾을 수 없습니다."
    if icode not in items:
        return "Item Code가 ERP에 등록되어 있지 않습니다."
    q = _number(qty)
    if q is None or not (q > 0) or not _is_int(q):
        return "수량 값이 올바르지 않습니다."
    if not re.match(r"^\d{4}-\d{2}-\d{2}$", dd) or _mkdate(int(dd[:4]), int(dd[5:7]), int(dd[8:10])) is None or dd < today:
        return "납기일 값이 올바르지 않습니다."
    return ""


def validate_order(email: dict, st: _State | None = None) -> str:
    """주문 검증 4종(고객·품목·수량·납기) — 문제 없으면 '' / order validation (customer, item, qty, date); '' when valid"""
    with _using(st) as s:
        en = email.get("entities") or {}
        v = lambda k: _s(_val(en, k)).strip()  # noqa: E731
        return _validate_values(v("customerCode"), v("itemCode"), v("quantity"), v("deliveryDate"), s.today, s.items)


def gen_so(case_id, st: _State) -> str:
    """Sales Order 번호 — 대표 시나리오 Case 의 첫 주문만 고정 00125, 그 밖(이미 쓴 뒤 포함)은 순번.
    SO number: only the scenario case's first order gets the fixed 00125; everything else (including later orders on
    that case) takes the next sequence number."""
    ymd = st.today.replace("-", "")
    fixed = f"SO-{ymd}-00125"
    if case_id == SCN_CASE and fixed not in st.shipments:
        return fixed
    return f"SO-{ymd}-{st.next_seq('so'):05d}"


def _order_price(st: _State, e: dict) -> int:
    en, c = e.get("entities") or {}, st.case(e.get("caseId"))
    r = erp_price(_sv(en, "customerCode"), _sv(en, "itemCode"), _number(_sv(en, "quantity")), st)
    return ((c or {}).get("entity", {}).get("unitPrice") or 0) if r.get("error") else r["price"]


def _erp_create(st: _State, cc: str, icode: str, qty, dd: str, item_name: str, case_id=None) -> dict:
    """출하 준비 등록 — 번호가 이미 있으면 같은 내용일 때만 그대로 쓰고, 다르면 충돌(409)로 막는다(섞인 데이터 방지).
    Register the shipment entry; an existing number is reused only for identical content, otherwise a 409 conflict."""
    so = gen_so(case_id, st)
    q = int(_number(qty))
    entry = {"so": so, "customerCode": cc, "itemCode": icode, "item": item_name, "orderQty": q, "shipQty": q,
             "shipDate": _add_days(dd, -2), "state": "출하 준비", "tracking": ""}
    old = st.shipments.get(so)
    if old is None:
        st.shipments[so] = entry
    elif any(old.get(k) != entry[k] for k in ("customerCode", "itemCode", "orderQty", "shipDate")):
        raise MailConflict(f"Sales Order {so} 는 이미 다른 내용으로 등록되어 있습니다.")
    return {"so": so, "shipment": copy.deepcopy(st.shipments[so])}


def erp_create_sales_order(customer_code, item_code, quantity, delivery_date, item_name="", case_id=None,
                           st: _State | None = None) -> dict:
    """Sales Order 생성(검증 → 번호 → 출하 준비 등록) / create a sales order (validate → number → shipment entry)"""
    with _using(st, write=True) as s:
        err = _validate_values(_s(customer_code).strip(), _s(item_code).strip(), quantity, _s(delivery_date).strip(),
                               s.today, s.items)
        if err:
            raise MailValidationError(err)
        cc, icode = _s(customer_code).strip(), _s(item_code).strip()
        r = _erp_create(s, cc, icode, quantity, _s(delivery_date).strip(), _s(item_name).strip() or s.items[icode]["short"],
                        case_id)
        price = erp_price(cc, icode, quantity, s).get("price")
        return {"so": r["so"], "customerCode": cc, "customer": ERP_CUSTOMERS[cc], "itemCode": icode,
                "item": r["shipment"]["item"], "qty": r["shipment"]["orderQty"], "date": _s(delivery_date).strip(),
                "price": price, "shipment": r["shipment"]}


def _mail_send(st: _State, to: str, subject: str, body: str, cc: str = "", attachments: list | None = None) -> dict:
    msg = {"messageId": f"MSG-{st.next_seq('msg'):05d}", "to": to, "cc": cc, "subject": subject, "body": body,
           "attachments": list(attachments or []), "sentAt": st.tick(0), "status": "sent"}
    st.outbox.append(msg)
    del st.outbox[:-_OUTBOX_MAX]
    return {"messageId": msg["messageId"], "status": "sent", "sentAt": msg["sentAt"], "to": to, "subject": subject}


def mail_send(to, subject, body, cc="", attachments=None, st: _State | None = None) -> dict:
    """가상 메일 발송 — 외부로 보내지 않고 발신함에 저장만 한다 / virtual mail send: stored in the outbox only"""
    to, subject, body = _s(to).strip(), _s(subject).strip(), _s(body)
    if "@" not in to:
        raise MailValidationError("받는 사람 주소가 올바르지 않습니다.")
    if not subject or not body.strip():
        raise MailValidationError("제목과 본문을 입력해 주세요.")
    with _using(st, write=True) as s:
        return _mail_send(s, to, subject, body, _s(cc), attachments)


