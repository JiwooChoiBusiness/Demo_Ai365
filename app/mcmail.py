def _apply_inbound(st: _State, e: dict) -> None:
    c = st.case(e.get("caseId"))
    if not c:
        return
    c["lastUpdatedDate"] = e.get("receivedDate")
    if _js(e.get("delta")):
        for d in e["delta"].get("changed") or []:
            c.setdefault("changes", []).append({"field": d["label"], "previousValue": d["prev"], "currentValue": d["cur"],
                                                "changedDate": e.get("receivedDate"), "sourceEmailId": e["emailId"]})
            c.setdefault("prev", {})[d["field"]] = c["entity"].get(d["field"])
            c["entity"][d["field"]] = d["raw"]
    if _js(e.get("caseStatus")):
        c["status"] = e["caseStatus"]
    if _js(e.get("caseRequest")):
        c["request"] = e["caseRequest"]


def _link(st: _State, e: dict, case_id: str) -> None:
    c = st.case(case_id)
    if not c:
        return
    e["caseId"] = case_id
    e["threadId"] = "T-" + case_id[-5:]
    e["assignee"] = c.get("assignedUser")
    en = e.setdefault("entities", {})
    new_q = _number(_val(en, "quantity"))
    if e.get("classification") == "quote" and _js(new_q) and new_q != c["entity"].get("quantity"):
        e["delta"] = {"changed": [{"field": "quantity", "label": "수량", "prev": f"{_s(c['entity'].get('quantity'))} EA",
                                   "cur": f"{_numstr(new_q)} EA", "raw": new_q}],
                      "kept": [{"label": "품목", "value": c["entity"].get("itemName")},
                               {"label": "납기", "value": c["entity"].get("deliveryDate")}],
                      "request": f"{_numstr(new_q)}EA 기준 단가 재확인"}
        e["caseStatus"] = "수정견적 필요"
        e["caseRequest"] = e["delta"]["request"]
        if isinstance(en.get("deliveryDate"), dict) and not _js(en["deliveryDate"].get("value")):
            en["deliveryDate"] = _F(c["entity"].get("deliveryDate"), .95, "case")
    if isinstance(en.get("salesOrder"), dict) and not _js(en["salesOrder"].get("value")) and _js(c.get("salesOrderNumber")):
        en["salesOrder"] = _F(c["salesOrderNumber"], .95, "case")
    _apply_inbound(st, e)
    st.add_log("ok", f"{e.get('customer')} · 담당자가 Case {case_id} 연결")


