def _js(v) -> bool:
    """JS 참/거짓 — 빈 배열·객체도 참 / JS truthiness (empty arrays and objects are truthy)"""
    if v is None or v is False:
        return False
    if v is True:
        return True
    if isinstance(v, (int, float)):
        return v != 0 and v == v
    if isinstance(v, str):
        return v != ""
    return True


_NUM_RE = re.compile(r"^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$")


def _number(v):
    """JS Number(v) — NaN 은 None, 빈 문자열은 0 / JS Number(v): NaN is None, the empty string is 0"""
    if v is None:
        return None
    if isinstance(v, bool):
        return int(v)
    if isinstance(v, (int, float)):
        return v if v == v else None
    s = str(v).strip()
    if s == "":
        return 0
    if not _NUM_RE.match(s):
        return None
    x = float(s)
    return int(x) if x.is_integer() and abs(x) < 2 ** 53 else x


def _is_int(x) -> bool:
    return isinstance(x, int) or (isinstance(x, float) and x.is_integer())


def _numstr(v) -> str:
    """JS String(number) — 정수는 소수점 없이 / JS String(number): integers without a decimal point"""
    if isinstance(v, float) and v.is_integer():
        return str(int(v))
    return str(v)


def _loc(n) -> str:
    """toLocaleString — 천 단위 쉼표 / toLocaleString with thousands separators"""
    x = _number(n)
    if x is None:
        return "NaN"
    if _is_int(x):
        return f"{int(x):,}"
    return f"{x:,.3f}".rstrip("0").rstrip(".")


def _round(x: float) -> int:
    """JS Math.round(양수) / JS Math.round for positive values"""
    return int(x + 0.5) if x >= 0 else -int(-x + 0.5)


def won(n) -> str:
    return _loc(n) + "원"


