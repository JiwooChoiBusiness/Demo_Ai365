def classify(email_id: str, classification: str, intent: str | None = None) -> dict:
    """분류 — intent 없이 미분류 메일이면 트리아지(tri-class), 아니면 분류 변경(modalReclass).
    Classify: triage path for an unclassified mail without intent, otherwise the reclassify modal path."""
    def fn(st: _State, e: dict) -> dict:
        _need_open(e, "완료된 메일은 분류를 변경할 수 없습니다.")
        if classification not in CLS:
            raise MailValidationError("알 수 없는 업무 유형입니다.")
        if intent is not None and intent not in INTENTS:
            raise MailValidationError("Email Intent 값이 올바르지 않습니다.")
        k = classification
        if intent is None and not _js(e.get("classification")):
            _set_class(st, e, k)
            return _tri_done(st, e, f"{CLS[k]['label']}(으)로 분류했습니다")
        it = intent if intent is not None else e.get("intent")
        if _js(it):
            e["intent"] = it
        if k != e.get("classification"):
            e["delta"] = None
            _set_class(st, e, k)
            if _js(it):
                e["intent"] = it
            _after_triage(st, e)
        return _toast("success", "분류 변경 완료", f"{CLS[k]['label']} · {_s(e.get('intent'))}")
    return _mail_action(email_id, fn)


def set_entity(email_id: str, field: str, value, triage: bool = False) -> dict:
    """추출 데이터 수정 — triage=False 는 자유 편집(입력창), True 는 확인 필요 해결(tri-set·tri-pick, 그 필드가 지금 확인
    필요 항목일 때만). 값은 저장할 때 앞뒤 공백을 뗀다. ERP 조회 뒤 조회 조건이 바뀌면 두 경로 모두 erpStale 을 켠다.
    Entity edit: triage=False is the info panel's free edit; True resolves a triage item (tri-set / tri-pick) and is
    accepted only while that field is an open review item. Values are trimmed on save; either path flags erpStale when a
    lookup key changes after the ERP lookup."""
    def fn(st: _State, e: dict) -> dict | None:
        _need_open(e, "완료된 메일은 수정할 수 없습니다.")
        if field not in FIELDS:
            raise MailValidationError("알 수 없는 항목입니다.")
        v = _s(value).strip()
        ents = e.setdefault("entities", {})
        if triage:
            if not any(i.get("field") == field for i in _issues(e)):
                raise MailValidationError("확인이 필요한 항목이 아닙니다.")
            if not v:
                raise MailValidationError("값을 입력해 주세요")
            cand = next((p for p in ((e.get("pick") or {}).get(field) or []) if p.get("value") == v), None)
            if cand is not None:
                _pick_value(st, e, field, cand)
                msg = f"{cand['value'] if field == 'salesOrder' else cand['label']} 선택"
            else:
                if field == "customerCode":
                    if v not in ERP_CUSTOMERS:
                        raise MailValidationError("Customer Code를 찾을 수 없습니다.")
                    _pick_value(st, e, field, {"value": v, "label": ERP_CUSTOMERS[v]})
                elif field == "itemCode":
                    if v not in st.items:
                        raise MailValidationError("Item Code가 ERP에 등록되어 있지 않습니다.")
                    _pick_value(st, e, field, {"value": v, "label": st.items[v]["short"]})
                else:
                    ents[field] = _F(v, 1, "user")
                    c = st.case(e.get("caseId"))
                    if c and field == "shippingAddress":
                        c["entity"]["shippingAddress"] = v
                msg = f"{FIELDS[field]} 확인"
            _mark_stale(e, field)
            return _tri_done(st, e, msg)
        ents[field] = _F(v, 1, "user")
        _mark_stale(e, field)
        if not _issues(e) and "확인 필요" in _s(e.get("workStatus")):
            _after_triage(st, e)
        return None
    return _mail_action(email_id, fn)


