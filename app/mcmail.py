def _register_error(st: _State, e: dict, category: str, failed_action: str, message: str) -> None:
    x = next((x for x in st.errors if x.get("emailId") == e["emailId"] and x.get("category") == category
              and x.get("status") == "open"), None)
    if x:
        x["message"] = message
        x["time"] = st.tick(0)
        x["tries"] = int(x.get("tries") or 0) + 1
    else:
        x = {"id": f"ERR-{st.next_seq('err'):04d}", "time": st.tick(0), "emailId": e["emailId"], "caseId": e.get("caseId") or "",
             "customer": e.get("customer"), "workType": e.get("classification"), "category": category,
             "failedAction": failed_action, "message": message, "status": "open", "assignee": e.get("assignee"), "tries": 1}
        st.errors.insert(0, x)
    c = st.case(e.get("caseId"))
    if c:
        c.setdefault("actions", []).append(_A(failed_action, "실패", st.tick(0), "", "", message))
    st.add_log("er", f"{e.get('customer')} · {failed_action} 실패")


def _resolve_errors(st: _State, e: dict, category: str) -> None:
    for x in st.errors:
        if x.get("emailId") == e["emailId"] and x.get("category") == category and x.get("status") == "open":
            x["status"] = "resolved"
            x["resolvedAt"] = st.tick(0)


# 오류 분류 → 그 오류를 다시 부를 흐름 단계 / error category → the flow step a retry would call again
_ERR_STEP = {"ERP 조회 실패": "erp", "ERP 주문등록 실패": "order", "Email 발송 실패": "mail"}


def _stale_error(e: dict, x: dict) -> bool:
    """재처리할 작업이 없는 미해결 오류인가 — 메일이 완료됐거나(완료·보관·스팸·주문등록·발송), 그 단계의 오류 상태가 사라졌다
    (분류 변경으로 flow 초기화 등). 발송 실패 표시(flow.mail='error')는 초안을 임시저장·다시 생성하거나 ERP 를 다시 조회해도
    실제 발송이 성공할 때까지 남으므로(_clear_mail_mark), 발송 실패 오류는 발송 성공·완료 계열·분류 변경으로만 닫힌다.
    Whether an open error has nothing left to retry: the mail is closed (complete, archive, spam, order entry, send) or
    that step's error state is gone (a reclassification reset the flow, ...). The failed-send mark (flow.mail='error')
    survives draft saves, regenerations and ERP re-queries until a send actually succeeds (_clear_mail_mark), so a
    send-failure error closes only on a successful send, a closing action or a reclassification."""
    step = _ERR_STEP.get(x.get("category"))
    return _js(e.get("closed")) or (step is not None and (e.get("flow") or {}).get(step) != "error")


def _clear_mail_mark(f: dict) -> None:
    """초안이 바뀌면 '임시저장됨' 표시(mail='saved'·draftSaved)를 지운다. 발송 실패(mail='error')는 발송이 아니므로 실제
    발송이 성공할 때까지 남긴다(서버 정책 — 원본 화면은 여기서 실패 표시까지 지웠다).
    A replaced draft drops the saved marks (mail='saved', draftSaved). A failed send (mail='error') is kept until a send
    actually succeeds, since editing a draft is not sending (server policy; the original page cleared it here too)."""
    if f.get("mail") != "error":
        f["mail"] = None
    f.pop("draftSaved", None)


def _settle_errors(st: _State, e: dict) -> int:
    """이 메일의 미해결 오류 중 재처리할 작업이 없는 것을 해결됨으로 닫는다(서버 정책 — 원본 화면은 목록·KPI·알림에 막다른
    오류를 영원히 남겼다). 액션마다 끝에서 부르므로 '미해결 오류 ⇔ 메일 상태 오류' 가 늘 맞는다. 닫은 건수를 돌려준다.
    Close this mail's open errors that have nothing left to retry (server policy: the original page kept such dead-end
    errors in the list, the KPI and the notices forever). Called at the end of every action, so 'open error ⇔ the mail
    shows an error' always holds. Returns how many were closed."""
    n = 0
    for x in st.errors:
        if x.get("emailId") == e.get("emailId") and x.get("status") == "open" and _stale_error(e, x):
            x["status"] = "resolved"
            x["resolvedAt"] = st.tick(0)
            n += 1
    return n


def _after_triage(st: _State, e: dict) -> bool:
    if _issues(e):
        return False
    c, k = st.case(e.get("caseId")), e.get("classification")
    e["userConfirmed"] = True
    if k == "order":
        ws = "ERP 전송대기"
    elif k != "quote" and k in ERPMETA:
        ws = ERPMETA[k]["ws"]
    elif k == "etc":
        ws = "기타 분류"
