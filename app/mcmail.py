# 메일 = rowid 오름차순(push), Case·오류 = rowid 내림차순(unshift). 갱신은 UPDATE 만(REPLACE 는 rowid 를 바꾼다).
# Store — each request loads the whole state (a few dozen rows) and writes back only changed rows. Row order mirrors
# the page's arrays: mails ascend by rowid (push), cases and errors descend (unshift). Updates are UPDATE only.
# ─────────────────────────────────────────────────────────────────────────────

_SCHEMA = """
CREATE TABLE IF NOT EXISTS mc_emails(
    email_id TEXT PRIMARY KEY, data TEXT NOT NULL, received_at TEXT, direction TEXT,
    case_id TEXT, classification TEXT, closed INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS mc_cases(case_id TEXT PRIMARY KEY, data TEXT NOT NULL, updated_at TEXT);
CREATE TABLE IF NOT EXISTS mc_errors(id TEXT PRIMARY KEY, data TEXT NOT NULL, time TEXT, status TEXT);
CREATE TABLE IF NOT EXISTS mc_log(seq INTEGER PRIMARY KEY AUTOINCREMENT, time TEXT, type TEXT, text TEXT);
CREATE TABLE IF NOT EXISTS mc_meta(key TEXT PRIMARY KEY, value TEXT);
"""


def _dumps(o) -> str:
    return json.dumps(o, ensure_ascii=False)


def _email_cols(e: dict) -> tuple:
    return (e.get("receivedDate") or "", e.get("direction") or "in", e.get("caseId") or "",
            e.get("classification") or "", 1 if e.get("closed") else 0)


class _State:
    """한 요청 동안의 메모리 상태 — 화면 JS 의 전역(EMAILS·CASES·ERRORS·LOG·SHIPMENTS·clock·seq)에 해당한다.
    In-memory state for one request — the counterpart of the page's globals."""

    def __init__(self, conn: sqlite3.Connection) -> None:
        self.conn = conn
        meta = {r[0]: r[1] for r in conn.execute("SELECT key, value FROM mc_meta")}
        self.today = meta.get("today") or _server_today().isoformat()
        self.clock = int(meta.get("clock") or _SEED.get("clock") or 722)
        self.seq = json.loads(meta.get("seq") or "null") or dict(_SEED.get("seq") or {})
        self.shipments = json.loads(meta.get("shipments") or "{}")
        self.outbox = json.loads(meta.get("outbox") or "[]")
        self._meta0 = self._meta_rows()
        self.items = _items_for(self.today)
        self.emails = [json.loads(r[0]) for r in conn.execute("SELECT data FROM mc_emails ORDER BY rowid")]
        self.cases = [json.loads(r[0]) for r in conn.execute("SELECT data FROM mc_cases ORDER BY rowid DESC")]
        self.errors = [json.loads(r[0]) for r in conn.execute("SELECT data FROM mc_errors ORDER BY rowid DESC")]
        self._snap_e = {e["emailId"]: _dumps(e) for e in self.emails}
        self._snap_c = {c["caseId"]: _dumps(c) for c in self.cases}
        self._snap_x = {x["id"]: _dumps(x) for x in self.errors}
        self.logs = [{"time": r[0], "type": r[1], "text": r[2]}
                     for r in conn.execute("SELECT time, type, text FROM mc_log ORDER BY seq DESC LIMIT ?", (_LOG_MAX,))]
        self.new_logs: list[dict] = []

    # ── 조회 헬퍼 / lookups ──
    def mail(self, email_id) -> dict | None:
        return next((e for e in self.emails if e.get("emailId") == email_id), None) if email_id else None

    def need_mail(self, email_id) -> dict:
        e = self.mail(email_id)
        if e is None:
            raise MailNotFound("메일을 찾을 수 없습니다.")
        return e

    def case(self, case_id) -> dict | None:
        return next((c for c in self.cases if c.get("caseId") == case_id), None) if case_id else None

    def inbound(self) -> list[dict]:
        return [e for e in self.emails if e.get("direction") == "in"]

    def open_errors(self) -> list[dict]:
        return [x for x in self.errors if x.get("status") == "open"]

    # ── 시각·로그 / clock and log ──
    def tick(self, minutes: int = 2) -> str:
        self.clock = min(self.clock + minutes, _CLOCK_MAX)
        return f"{self.today} {_hhmm(self.clock)}"

    def add_log(self, kind: str, text: str) -> None:
        entry = {"time": _hhmm(self.clock), "type": kind, "text": text}
        self.new_logs.append(entry)
        self.logs.insert(0, entry)
        del self.logs[_LOG_MAX:]

    def next_seq(self, key: str) -> int:
        self.seq[key] = int(self.seq.get(key) or 0) + 1
        return self.seq[key]

    # ── 저장 / save ──
    def _meta_rows(self) -> dict:
        return {"today": self.today, "clock": str(self.clock), "seq": _dumps(self.seq),
                "shipments": _dumps(self.shipments), "outbox": _dumps(self.outbox)}

    def save(self) -> None:
        c = self.conn
        for e in self.emails:
            js, old = _dumps(e), self._snap_e.get(e["emailId"])
            if old is None:
                c.execute("INSERT INTO mc_emails(email_id, data, received_at, direction, case_id, classification, closed)"
                          " VALUES (?,?,?,?,?,?,?)", (e["emailId"], js, *_email_cols(e)))
            elif old != js:
                c.execute("UPDATE mc_emails SET data=?, received_at=?, direction=?, case_id=?, classification=?, closed=?"
                          " WHERE email_id=?", (js, *_email_cols(e), e["emailId"]))
        for x in reversed([x for x in self.cases if x["caseId"] not in self._snap_c]):
            c.execute("INSERT INTO mc_cases(case_id, data, updated_at) VALUES (?,?,?)",
                      (x["caseId"], _dumps(x), x.get("lastUpdatedDate") or ""))
        for x in self.cases:
            old = self._snap_c.get(x["caseId"])
            if old is not None and old != _dumps(x):
                c.execute("UPDATE mc_cases SET data=?, updated_at=? WHERE case_id=?",
                          (_dumps(x), x.get("lastUpdatedDate") or "", x["caseId"]))
        for x in reversed([x for x in self.errors if x["id"] not in self._snap_x]):
            c.execute("INSERT INTO mc_errors(id, data, time, status) VALUES (?,?,?,?)",
                      (x["id"], _dumps(x), x.get("time") or "", x.get("status") or ""))
        for x in self.errors:
            old = self._snap_x.get(x["id"])
            if old is not None and old != _dumps(x):
                c.execute("UPDATE mc_errors SET data=?, time=?, status=? WHERE id=?",
                          (_dumps(x), x.get("time") or "", x.get("status") or "", x["id"]))
        rows = self._meta_rows()
        for k, v in rows.items():
            if self._meta0.get(k) != v:
                c.execute("INSERT INTO mc_meta(key, value) VALUES (?, ?) ON CONFLICT(key) DO UPDATE SET value=excluded.value",
                          (k, v))
        for entry in self.new_logs:
            c.execute("INSERT INTO mc_log(time, type, text) VALUES (?,?,?)", (entry["time"], entry["type"], entry["text"]))
        if self.new_logs:
            c.execute("DELETE FROM mc_log WHERE seq NOT IN (SELECT seq FROM mc_log ORDER BY seq DESC LIMIT ?)", (_LOG_MAX,))

    # ── 액션 응답 / action payload ──
    def payload(self, e: dict | None, toast: dict | None, case: dict | None = None) -> dict:
        c = case if case is not None else (self.case(e.get("caseId")) if e else None)
        return {"email": public(e, self) if e else None, "case": public_case(c) if c else None,
                "errors": copy.deepcopy(self.open_errors()), "log": copy.deepcopy(self.logs[:_LOG_MAX]),
                "toast": toast, "nav": _nav(self)}


@contextmanager
def _tx():
    """쓰기 트랜잭션 — 스키마를 보장한 뒤 BEGIN IMMEDIATE 로 DB 쓰기 잠금을 잡고, 끝나면 커밋·실패하면 롤백.
    Write transaction: ensure the schema, take the DB write lock with BEGIN IMMEDIATE, commit (or roll back on error)."""
    conn = db._conn()  # noqa: SLF001 — 프로젝트 관례(스토어 모듈은 db._conn 공유) / project convention
    try:
        conn.executescript(_SCHEMA)       # 멱등 DDL, executescript 는 스스로 커밋한다 / idempotent DDL; executescript commits itself
        conn.execute("BEGIN IMMEDIATE")
        yield conn
        conn.commit()
    except BaseException:
        conn.rollback()
        raise
    finally:
        conn.close()


@contextmanager
def _session(write: bool = False):
    """잠금 + 상태 적재 + (쓰기면) 저장, 끝나면 커밋·실패하면 롤백. 쓰기는 상태를 읽기 전에 BEGIN IMMEDIATE 로 DB 쓰기
    잠금을 잡는다 — _LOCK 은 한 프로세스 안에서만 유효해서, 같은 DB 를 쓰는 다른 서버 프로세스(8000·8010)와 읽기-수정-쓰기가
    겹치면 같은 번호(E-3043 등)를 두 번 배정한다. 읽기는 BEGIN 으로 한 시점의 상태를 본다.
    Lock + load + save on write, then commit (roll back on error). Writes take the DB write lock with BEGIN IMMEDIATE
    before loading: _LOCK only serializes threads of one process, and another server process on the same DB would
    otherwise interleave its read-modify-write and hand out the same ids twice. Reads see one snapshot via BEGIN."""
    begin = "BEGIN IMMEDIATE" if write else "BEGIN"
    with _LOCK:
        conn = db._conn()  # noqa: SLF001
        try:
            conn.execute(begin)
            try:
                st = _State(conn)
            except sqlite3.OperationalError as exc:
                # 스키마가 없을 때만(init 전 호출) 만들고 시드한 뒤 다시 읽는다 — 잠김 같은 다른 오류는 그대로 올린다
                # (그렇지 않으면 세션 중에 재기준이 돌 수 있다)
                # only a missing schema (called before init) creates, seeds and reloads; any other error such as a locked
                # database propagates (otherwise a re-anchor could run in the middle of a session)
                if "no such table" not in str(exc):
                    raise
                conn.rollback()
                conn.executescript(_SCHEMA)
                conn.execute("BEGIN IMMEDIATE")
                _init_conn(conn)
                conn.commit()
                conn.execute(begin)
                st = _State(conn)
            yield st
            if write:
                st.save()
            conn.commit()
        except BaseException:
            conn.rollback()
            raise
        finally:
            conn.close()


def _seed_into(conn: sqlite3.Connection, today: date) -> None:
    """시드를 오늘 기준으로 복원해 넣는다(기존 행은 비운다) / restore the seed to today and insert it (clears old rows)"""
    data = _restore(copy.deepcopy({k: _SEED.get(k) for k in ("EMAILS", "CASES", "ERRORS", "LOG", "SHIPMENTS")}), today)
    for t in ("mc_emails", "mc_cases", "mc_errors", "mc_log", "mc_meta"):
        conn.execute(f"DELETE FROM {t}")  # noqa: S608 — 고정 테이블명 / fixed table names
    for e in data["EMAILS"] or []:
        conn.execute("INSERT INTO mc_emails(email_id, data, received_at, direction, case_id, classification, closed)"
                     " VALUES (?,?,?,?,?,?,?)", (e["emailId"], _dumps(e), *_email_cols(e)))
    for c in reversed(data["CASES"] or []):
        conn.execute("INSERT INTO mc_cases(case_id, data, updated_at) VALUES (?,?,?)",
                     (c["caseId"], _dumps(c), c.get("lastUpdatedDate") or ""))
    for x in reversed(data["ERRORS"] or []):
        conn.execute("INSERT INTO mc_errors(id, data, time, status) VALUES (?,?,?,?)",
                     (x["id"], _dumps(x), x.get("time") or "", x.get("status") or ""))
    for entry in reversed(data["LOG"] or []):
        conn.execute("INSERT INTO mc_log(time, type, text) VALUES (?,?,?)", (entry["time"], entry["type"], entry["text"]))
    meta = {"today": today.isoformat(), "clock": str(_SEED.get("clock") or 722), "seq": _dumps(_SEED.get("seq") or {}),
            "shipments": _dumps(data["SHIPMENTS"] or {}), "outbox": "[]",
            _DASH_FLAG: "1"}   # 새 시드에는 옛 em dash 문구가 없다 / the current seed holds no old em dash wording
    conn.executemany("INSERT INTO mc_meta(key, value) VALUES (?, ?)", list(meta.items()))


def _reanchor(conn: sqlite3.Connection, today: date) -> None:
    """이미 시드된 DB 의 날짜를 저장된 기준일→오늘만큼 옮긴다(진행 상태는 보존) / shift a seeded DB to today, keeping progress"""
    row = conn.execute("SELECT value FROM mc_meta WHERE key='today'").fetchone()
    new = today.isoformat()
    if row is None or not row[0]:
        conn.execute("INSERT INTO mc_meta(key, value) VALUES ('today', ?) ON CONFLICT(key) DO UPDATE SET value=excluded.value",
                     (new,))
        return
    if row[0] == new:
        return
    try:
        old = date.fromisoformat(row[0])
    except ValueError:
        # 저장값이 깨졌으면 옮기지 않고 기준일만 고친다(기동을 막지 않는다) / broken value: fix the anchor, never block startup
        logger.warning("mcmail 기준일 값이 올바르지 않습니다 / bad stored anchor: %r", row[0])
        conn.execute("UPDATE mc_meta SET value=? WHERE key='today'", (new,))
        return
    for eid, data in conn.execute("SELECT email_id, data FROM mc_emails").fetchall():
        e = _shift(json.loads(data), old, today)
        conn.execute("UPDATE mc_emails SET data=?, received_at=?, direction=?, case_id=?, classification=?, closed=?"
                     " WHERE email_id=?", (_dumps(e), *_email_cols(e), eid))
    for cid, data in conn.execute("SELECT case_id, data FROM mc_cases").fetchall():
        c = _shift(json.loads(data), old, today)
        conn.execute("UPDATE mc_cases SET data=?, updated_at=? WHERE case_id=?", (_dumps(c), c.get("lastUpdatedDate") or "", cid))
    for xid, data in conn.execute("SELECT id, data FROM mc_errors").fetchall():
        x = _shift(json.loads(data), old, today)
        conn.execute("UPDATE mc_errors SET data=?, time=? WHERE id=?", (_dumps(x), x.get("time") or "", xid))
    for seq, text in conn.execute("SELECT seq, text FROM mc_log").fetchall():
        conn.execute("UPDATE mc_log SET text=? WHERE seq=?", (_shift(text or "", old, today), seq))
    for key in ("shipments", "outbox"):
        r = conn.execute("SELECT value FROM mc_meta WHERE key=?", (key,)).fetchone()
        if r and r[0]:
            conn.execute("UPDATE mc_meta SET value=? WHERE key=?", (_dumps(_shift(json.loads(r[0]), old, today)), key))
    conn.execute("UPDATE mc_meta SET value=? WHERE key='today'", (new,))
    logger.info("mcmail 기준일 이동 / re-anchored %s -> %s", old, new)


