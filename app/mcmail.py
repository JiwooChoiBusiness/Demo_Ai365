_CASE_FILTERS = ("all", "견적", "주문", "문의", "open", "done")


def list_cases(filter: str = "all", q: str = "", date_from: str | None = None, date_to: str | None = None) -> dict:  # noqa: A002
    """화면 caseList — 최종 업데이트 최신순 / the page's case list, newest update first"""
    if filter not in _CASE_FILTERS:
        raise MailValidationError("알 수 없는 필터입니다.")
    lo, hi = _norm_date(date_from, "시작일"), _norm_date(date_to, "종료일")
    ql = (q or "").strip().lower()
    with _session() as st:
        def match(c: dict) -> bool:
            if filter == "all":
                return True
            if filter == "open":
                return not _case_done(c)
            if filter == "done":
                return _case_done(c)
            return filter in _s(c.get("caseType"))

        def hay(c: dict) -> str:
            return " ".join(_s(x) for x in (c.get("caseId"), c.get("customer"), c.get("title"), (c.get("entity") or {}).get("itemName"),
                                            c.get("salesOrderNumber"), c.get("assignedUser"))).lower()

        rows = [c for c in st.cases if _in_range(c.get("lastUpdatedDate"), lo, hi) and match(c) and (not ql or ql in hay(c))]
        rows = sorted(rows, key=lambda c: _s(c.get("lastUpdatedDate")), reverse=True)
        return {"filter": filter, "items": [public_case(c) for c in rows], "total": len(rows)}


