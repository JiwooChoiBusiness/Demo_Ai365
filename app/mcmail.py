# 날짜 토큰 — 시드는 기준일 대비 일 수로 저장하고, 시드·재기준 때 오늘로 되돌린다.
# 형식: [[D±n]] YYYY-MM-DD · [[C±n]] YYYYMMDD(SO·INV 번호·파일명) · [[Y±n]] YYYY-MM(n=개월) · [[K±n]] 'M월 D일' ·
#       [[S±n]] 'M/D'(납기 문맥) · [[M±n]] MMDD(파일명) · [[E±n]] 'October 15'(EN 초안)
# Date tokens — the seed stores day offsets from the base day; seed and re-anchor restore them to today.
# Forms: D=ISO date, C=compact date in SO/INV numbers and file names, Y=year-month (n in months), K=Korean
# month-day, S=slash month/day next to '납기', M=MMDD in file names, E=English month-day of EN drafts.
# ─────────────────────────────────────────────────────────────────────────────

_MONTHS_EN = ("January", "February", "March", "April", "May", "June", "July", "August", "September",
              "October", "November", "December")
_ISO_RE = re.compile(r"(?<!\d)(\d{4})-(\d{2})-(\d{2})(?!\d)")
_C8_RE = re.compile(r"(?:(?<=SO-)|(?<=INV-)|(?<=_))(\d{4})(\d{2})(\d{2})(?!\d)")
_YM_RE = re.compile(r"(?<!\d)(\d{4})-(\d{2})(?![-\d])")
_KO_RE = re.compile(r"(?<!\d)(\d{1,2})월 ?(\d{1,2})일")
_SL_RE = re.compile(r"(?<![\d/])(\d{1,2})/(\d{1,2})(?![\d/])(?= 납기)|(?<=납기 )(\d{1,2})/(\d{1,2})(?![\d/])")
_MD_RE = re.compile(r"(?<=_)(\d{2})(\d{2})(?=\.[A-Za-z0-9]{2,5}\b)")
_EN_RE = re.compile(r"\b(" + "|".join(_MONTHS_EN) + r") (\d{1,2})\b")
_TOKEN_RE = re.compile(r"\[\[([DCYKSME])([+-]\d+)\]\]")


def _mkdate(y: int, m: int, d: int) -> date | None:
    try:
        return date(y, m, d)
    except ValueError:
        return None


def _nearest(anchor: date, month: int, day: int) -> date | None:
    """연도가 없는 월·일 → 기준일에 가장 가까운 날짜 / month-day without a year → the date nearest the anchor"""
    best = None
    for y in (anchor.year - 1, anchor.year, anchor.year + 1):
        d = _mkdate(y, month, day)
        if d and (best is None or abs((d - anchor).days) < abs((best - anchor).days)):
            best = d
    return best


def _tok_str(s: str, anchor: date) -> str:
    """문자열 안의 날짜를 anchor 대비 토큰으로 바꾼다 / replace the dates in a string with anchor-relative tokens"""
    def day_tok(kind: str, d: date | None, raw: str) -> str:
        return raw if d is None else f"[[{kind}{(d - anchor).days:+d}]]"

    s = _ISO_RE.sub(lambda m: day_tok("D", _mkdate(int(m[1]), int(m[2]), int(m[3])), m[0]), s)
    s = _C8_RE.sub(lambda m: day_tok("C", _mkdate(int(m[1]), int(m[2]), int(m[3])), m[0]), s)

    def ym(m: re.Match) -> str:
        y, mo = int(m[1]), int(m[2])
        if not (2000 <= y <= 2099 and 1 <= mo <= 12):
            return m[0]
        return f"[[Y{(y * 12 + mo - 1) - (anchor.year * 12 + anchor.month - 1):+d}]]"

    s = _YM_RE.sub(ym, s)
    s = _KO_RE.sub(lambda m: day_tok("K", _nearest(anchor, int(m[1]), int(m[2])), m[0]), s)

    def sl(m: re.Match) -> str:
        mo, d = (m[1], m[2]) if m[1] else (m[3], m[4])
        return day_tok("S", _nearest(anchor, int(mo), int(d)), m[0])

    s = _SL_RE.sub(sl, s)
    s = _MD_RE.sub(lambda m: day_tok("M", _nearest(anchor, int(m[1]), int(m[2])), m[0]), s)
    return _EN_RE.sub(lambda m: day_tok("E", _nearest(anchor, _MONTHS_EN.index(m[1]) + 1, int(m[2])), m[0]), s)


def _res_str(s: str, today: date) -> str:
    """토큰 → 오늘 기준 날짜 문자열 / tokens → date strings relative to today"""
    if "[[" not in s:
        return s

    def rep(m: re.Match) -> str:
        kind, n = m[1], int(m[2])
        if kind == "Y":
            total = today.year * 12 + today.month - 1 + n
            return f"{total // 12:04d}-{total % 12 + 1:02d}"
        d = today + timedelta(days=n)
        if kind == "D":
            return d.isoformat()
        if kind == "C":
            return d.strftime("%Y%m%d")
        if kind == "K":
            return f"{d.month}월 {d.day}일"
        if kind == "S":
            return f"{d.month}/{d.day}"
        if kind == "M":
            return f"{d.month:02d}{d.day:02d}"
        return f"{_MONTHS_EN[d.month - 1]} {d.day}"

    return _TOKEN_RE.sub(rep, s)


def _walk(o, fn):
    """JSON 트리의 문자열(키 포함)에 fn 적용 / apply fn to every string of a JSON tree, keys included"""
    if isinstance(o, str):
        return fn(o)
    if isinstance(o, list):
        return [_walk(v, fn) for v in o]
    if isinstance(o, dict):
        return {(fn(k) if isinstance(k, str) else k): _walk(v, fn) for k, v in o.items()}
    return o


def _tokenize(obj, anchor: date):
    """절대 날짜 → 토큰 — 시드 JSON 에 날짜가 든 값을 새로 넣을 때 쓰는 도우미(예: _tokenize(값, date(2026, 9, 20))).
    Absolute dates → tokens; a helper for adding dated values to the seed JSON by hand (e.g. with base 2026-09-20)."""
    return _walk(obj, lambda s: _tok_str(s, anchor))


def _restore(obj, today: date):
    """토큰 → 오늘 기준 절대 날짜 / tokens → absolute dates relative to today"""
    return _walk(obj, lambda s: _res_str(s, today))


# 재기준 이스케이프 — 저장된 값에는 사용자가 쓴 글(초안·배송지 등)이 섞여 있어 '[[D+3]]' 같은 글자가 토큰으로 오인될 수
# 있다. 옮기기 전에 모든 '[' 를 사용 영역 문자 쌍으로 바꿔 두면 이 모듈이 만든 토큰만 날짜로 되돌아간다('[' 와 같은
# 비숫자·비단어 문자라 날짜 인식 경계도 그대로다).
# Re-anchor escaping — stored values mix in user text (drafts, addresses, ...) where '[[D+3]]' could pass for a token.
# Every '[' is swapped for a private-use pair before the shift, so only the tokens this module makes turn into dates
# (the pair is non-digit and non-word like '[', so date boundaries stay the same).
_ESC = "\ue000"
_UNESC_RE = re.compile(_ESC + "(.)", re.S)


def _esc(s: str) -> str:
    return s.replace(_ESC, _ESC + _ESC).replace("[", _ESC + "(")


def _unesc(s: str) -> str:
    return _UNESC_RE.sub(lambda m: _ESC if m[1] == _ESC else "[", s)


def _shift(obj, old: date, new: date):
    """저장된 날짜를 old→new 차이만큼 옮긴다 — 사용자 글의 '[[…]]' 는 그대로 둔다.
    Move stored dates by the old→new difference; user text such as '[[…]]' is left as typed."""
    return _walk(obj, lambda s: _unesc(_res_str(_tok_str(_esc(s), old), new)))


