def _next_step(e: dict) -> dict:
    f, n, k = e.get("flow") or {}, e.get("needs") or [], e.get("classification")
    if _js(e.get("closed")):
        return {"k": "none", "label": "완료", "title": "처리 완료"}
    if not _js(k):
        return {"k": "class", "label": "유형 선택", "title": "업무 유형 선택"}
    iss = _issues(e)
    if iss:
        return {"k": "triage", "label": "항목 확인", "title": f"확인 필요 {len(iss)}건"}
    if _js(e.get("hold")):
        return {"k": "hold", "label": "보류 해제", "title": "보류 해제"}
    ae = _api_err(e)
    if ae:
        return {"k": "retry", "label": "다시 시도",
                "title": "ERP 다시 조회" if ae == "erp" else "ERP로 다시 전송" if ae == "order" else "메일 다시 발송"}
    if k == "etc":
        return {"k": "etc", "label": "보관", "title": "보관"}
    if "erp" in n and f.get("erp") != "done":
        title = ("ERP 단가 재조회 후 수정 견적 작성" if k == "quote" and _js(e.get("delta"))
                 else "ERP Sales Order 조회 후 인보이스 메일 작성" if k == "invoice"
                 else (ERPMETA.get(k) or {}).get("act", "") + " 후 답변 작성")
        return {"k": "erp", "label": "ERP 조회", "title": title}
    if "order" in n and f.get("order") != "done":
        return {"k": "order", "label": "주문등록", "title": "ERP 주문등록"}
    if "reply" in n:
        if not _js(f.get("draft")):
            return {"k": "draft", "label": "메일 작성", "title": "AI 답변 생성"}
        if f.get("mail") != "sent":
            return {"k": "send", "label": "메일 발송", "title": "이메일 발송"}
    return {"k": "close", "label": "확인 완료", "title": "확인 완료"}


def _work_steps(e: dict) -> list:
    f, k = e.get("flow") or {}, e.get("classification")
    if k == "order":
        return [["주문 내용 확인", f.get("order") in ("done", "loading")], ["ERP 주문등록", f.get("order") == "done"],
                ["주문확인 메일 (선택)", f.get("mail") == "sent"]]
    if not (e.get("needs") or []):
        return []
    first = "ERP 단가 재조회" if k == "quote" and _js(e.get("delta")) else (ERPMETA.get(k) or {}).get("act", "")
    return [[first, f.get("erp") == "done"], ["인보이스 메일 작성" if k == "invoice" else "AI 답변 작성", _js(f.get("draft"))],
            ["확인 후 발송", f.get("mail") == "sent"]]


