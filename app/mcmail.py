# em dash 정리(2026-09-29). 화면 문구는 em dash 를 쓰지 않는다(이름과 제목 사이는 ' · ', 문장 안은 쌍점·쉼표). 이미 시드된
# DB 에 남은 옛 문구(옛 시드 JSON 의 메일 제목·오류 문구·활동 기록, 옛 코드가 쓴 활동 기록·재고 안내 초안과 그 발송본)는
# init 때 한 번만 새 문구로 바꾼다(mc_meta 'dash_cleanup_v1'). 문자열 값만 고치고 날짜·상태·다른 필드와 색인 열은 그대로 둔다.
# Em dash cleanup (2026-09-29). UI text uses no em dash (' · ' between a name and a title, a colon or a comma inside a
# sentence). Old wording left in an already seeded DB (mail subjects, error texts and log lines from the old seed JSON;
# log lines, stock drafts and their sent copies written by the old code) is rewritten once at init, guarded by mc_meta
# 'dash_cleanup_v1'. Only string values change; dates, statuses, other fields and the indexed columns stay as they are.
# ─────────────────────────────────────────────────────────────────────────────

_EM = "\u2014"   # 코드에는 이스케이프로만 둔다 / kept in code as an escape only
_DASH_FLAG = "dash_cleanup_v1"
# 옛 문구 → 새 문구(시드 JSON·코드에서 바꾼 것과 같은 대응) / old → new wording, the same mapping as the seed and code edits
_DASH_FIXES = ((f"SMTP 451 Temporary failure {_EM} 수신 서버 응답 지연", "SMTP 451 Temporary failure: 수신 서버 응답 지연"),
               (f"부족 {_EM} 다음 입고 ", "부족, 다음 입고 "))


def _undash(s: str) -> str:
    """옛 em dash 문구 → 새 문구. 알려진 문구를 먼저 바꾸고, 남은 것은 앞뒤 공백이 있으면 ' · ', 없으면 '-'.
    Old em dash wording → new: known phrases first, then a remaining spaced dash becomes ' · ' and a bare one '-'."""
    if _EM not in s:
        return s
    for old, new in _DASH_FIXES:
        s = s.replace(old, new)
    return s.replace(f" {_EM} ", " · ").replace(_EM, "-")


def _dash_cleanup(conn: sqlite3.Connection) -> int:
    """(호출자가 스키마와 쓰기 잠금을 잡은 상태에서) 옛 em dash 문구를 한 번만 바꾸고 바꾼 행 수를 돌려준다. 정리 표시가
    이미 있으면 아무것도 읽거나 쓰지 않는다(-1).
    With the schema and write lock held by the caller, rewrite the old em dash wording once and return the number of
    changed rows. When the flag is already set nothing is read or written (-1)."""
    if conn.execute("SELECT 1 FROM mc_meta WHERE key=?", (_DASH_FLAG,)).fetchone():
        return -1
    n = 0
    for table, key in (("mc_emails", "email_id"), ("mc_cases", "case_id"), ("mc_errors", "id")):
        for rid, data in conn.execute(f"SELECT {key}, data FROM {table}").fetchall():  # noqa: S608 (고정 이름 / fixed names)
            old = json.loads(data)
            new = _walk(old, _undash)
            if new != old:
                conn.execute(f"UPDATE {table} SET data=? WHERE {key}=?", (_dumps(new), rid))  # noqa: S608
                n += 1
    for seq, text in conn.execute("SELECT seq, text FROM mc_log").fetchall():
        if text and _EM in text:
            conn.execute("UPDATE mc_log SET text=? WHERE seq=?", (_undash(text), seq))
            n += 1
    for k in ("shipments", "outbox"):
        r = conn.execute("SELECT value FROM mc_meta WHERE key=?", (k,)).fetchone()
        if r and r[0]:
            old = json.loads(r[0])
            new = _walk(old, _undash)
            if new != old:
                conn.execute("UPDATE mc_meta SET value=? WHERE key=?", (_dumps(new), k))
                n += 1
    conn.execute("INSERT INTO mc_meta(key, value) VALUES (?, '1') ON CONFLICT(key) DO UPDATE SET value=excluded.value",
                 (_DASH_FLAG,))
    if n:
        logger.info("mcmail em dash 정리 / em dash cleanup: %d rows", n)
    return n


def _init_conn(conn: sqlite3.Connection) -> None:
    """(호출자가 스키마와 쓰기 잠금을 잡은 상태에서) 비어 있으면 시드, 아니면 오늘로 재기준. 이어서 옛 em dash 문구를 한 번 정리한다.
    With the schema and write lock held by the caller: seed when empty, else re-anchor to today; then the one-time em dash
    cleanup."""
    if conn.execute("SELECT COUNT(*) FROM mc_emails").fetchone()[0] == 0:
        _seed_into(conn, _server_today())
    else:
        _reanchor(conn, _server_today())
    _dash_cleanup(conn)


def init_mcmail() -> None:
    """테이블 생성 + 비어 있으면 시드(아니면 오늘로 재기준) + 옛 em dash 문구 1회 정리
    Create tables, seed when empty (else re-anchor to today), then the one-time em dash cleanup."""
    with _LOCK, _tx() as conn:
        _init_conn(conn)


