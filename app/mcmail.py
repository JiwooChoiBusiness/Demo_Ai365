def _def_needs(cls) -> list:
    return ["order"] if cls == "order" else [] if cls == "etc" or not _js(cls) else ["erp", "reply"]


def _issues(e: dict) -> list[dict]:
    if _js(e.get("closed")):
        return []
    k = e.get("classification")
    if not _js(k):
        return [{"k": "class"}]
    if k == "etc":
        return []
    out = []
    ents = e.get("entities") or {}
    for fld in REQUIRED.get(k) or []:
        f = ents.get(fld)
        if not isinstance(f, dict) or not _s(f.get("value")).strip():
            out.append({"k": "field", "field": fld, "missing": True})
        elif f.get("src") != "user" and (f.get("conf") or 0) < .8:
            out.append({"k": "field", "field": fld, "low": True})
    if not _js(e.get("caseId")) and k not in CASE_OPTIONAL:
        out.append({"k": "case"})
    return out


def _api_err(e: dict) -> str:
    f = e.get("flow") or {}
    return "erp" if f.get("erp") == "error" else "order" if f.get("order") == "error" else "mail" if f.get("mail") == "error" else ""


def _has_flow(e: dict) -> bool:
    f = e.get("flow") or {}
    return any(_js(f.get(k)) for k in ("erp", "order", "draft", "mail"))


def _status(e: dict) -> str:
    if _js(e.get("closed")):
        return "완료"
    if not _js(e.get("classification")):
        return "미분류"
    if _issues(e):
        return "확인 필요"
    if _api_err(e):
        return "오류"
    if _js(e.get("hold")):
        return "보류"
    return "진행 중" if _has_flow(e) else "처리 대기"


def _in_triage(e: dict) -> bool:
    return _status(e) in ("미분류", "확인 필요")


# 상태 7종 → 배지 색 계열(화면 STATUS_TONE) / the seven statuses → badge tone (the page's STATUS_TONE)
