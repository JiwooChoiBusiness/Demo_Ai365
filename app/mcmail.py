def _nav(st: _State) -> dict:
    inb = st.inbound()
    out = {"inbox": sum(1 for e in inb if _in_triage(e)), "errors": len(st.open_errors())}
    for v in MAIL_VIEWS[1:]:
        out[v] = sum(1 for e in _list_base(st, v) if not _js(e.get("closed")))
    out["notif"] = out["inbox"] + out["errors"]
    return out


