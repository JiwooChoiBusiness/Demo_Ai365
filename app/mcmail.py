def assign(kind: str, id: str, user: str) -> dict:  # noqa: A002 — 화면 계약 이름 / the page's contract name
    """담당자 지정 — Case·열린 메일·미해결 오류에 함께 반영 / assign; propagates to the case, open mails and open errors"""
    if kind not in ("mail", "case"):
        raise MailValidationError("kind는 mail 또는 case 여야 합니다.")
    if user not in [u.get("name") for u in USERS]:
        raise MailValidationError("담당자를 찾을 수 없습니다.")
    with _session(write=True) as st:
        tgt = st.case(id) if kind == "case" else st.mail(id)
        if tgt is None:
            raise MailNotFound("Case를 찾을 수 없습니다." if kind == "case" else "메일을 찾을 수 없습니다.")
        cid = id if kind == "case" else tgt.get("caseId")
