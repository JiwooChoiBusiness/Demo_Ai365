def _timeline(st: _State, c: dict) -> list[dict]:
    items = [{"t": m.get("receivedDate"), "type": "mail", "emailId": m["emailId"]} for m in _case_mails(st, c["caseId"])]
    items += [{"t": a.get("completedDate") or a.get("requestedDate"), "type": "action", "action": copy.deepcopy(a)}
              for a in c.get("actions") or [] if "ERP" in _s(a.get("actionType"))]
