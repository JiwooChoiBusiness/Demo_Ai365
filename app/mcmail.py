def _close_mail(st: _State, e: dict, label: str | None) -> None:
    e["closed"] = True
    e["hold"] = False
    ws = e.get("workStatus") or ""
    if label:
        e["workStatus"] = label
    elif "완료" not in ws and ws != "고객 검토 중":
        e["workStatus"] = "처리완료"
    st.add_log("ok", f"{e.get('customer')} · {label or '확인 완료'}")


def _run_draft(st: _State, e: dict, regen: bool, lang: str) -> None:
    f = e.setdefault("flow", {})
    f["variant"] = (f.get("variant") or 0) + 1 if regen else (f.get("variant") or 0)
    needs = e.setdefault("needs", [])
    if "reply" not in needs:
        needs.append("reply")
    f["draft"] = make_draft(e, f["variant"], lang)
    f["draftState"] = "ready"
    _clear_mail_mark(f)   # 새 초안 — 발송 실패 표시는 발송 성공 때까지 남긴다 / new draft; a failed send stays marked
    if not _js(e.get("closed")):
        e["workStatus"] = "답변 검토 중"


def _auto_complete(st: _State, e: dict, lang: str = "ko") -> None:
    if _js(e.get("closed")):
        return
    f, needs = e.setdefault("flow", {}), e.get("needs") or []
    if "erp" in needs and f.get("erp") != "done":
        _apply_erp(st, e)
    if "order" in needs and f.get("order") != "done":
        _apply_order(st, e)
    if "reply" in needs and f.get("mail") != "sent" and _draft_ready(e):
        if not _js(f.get("draft")):
            f["draft"] = make_draft(e, 0, lang)
        _apply_send(st, e)
    if not _js(e.get("closed")):
        _close_mail(st, e, None)


def _do_erp(st: _State, e: dict, lang: str) -> dict:
    """화면 runErp — 조회 후 답장이 필요하면 초안까지 이어서 / the page's runErp, chaining the draft when a reply is due"""
    k = e.get("classification")
    if not _apply_erp(st, e):
        return _toast("error", "ERP 조회 실패", _s(e["flow"].get("erpError")))
    if "reply" in (e.get("needs") or []) and e["flow"].get("mail") != "sent":
        _run_draft(st, e, False, lang)
        return _toast("success", ERPMETA[k]["done"], _DRAFT_MSG_INV if k == "invoice" else _DRAFT_MSG)
    return _toast("success", ERPMETA[k]["done"], "")


def _do_order(st: _State, e: dict) -> dict:
    if _apply_order(st, e):
        return _toast("success", "주문등록 완료", f"Sales Order {e['flow']['orderResult']['so']}")
    return _toast("error", "ERP 전송 실패", f"{e['flow'].get('orderError')} 주문은 등록되지 않았습니다.")


def _do_send(st: _State, e: dict) -> dict:
    _apply_send(st, e)
    return _toast("success", "이메일 발송 완료", f"{_s(e.get('sender'))} 에게 발송했습니다.")


